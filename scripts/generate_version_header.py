"""
generate_version_header.py
CLICOM -- Generate clip_version.h from version constants.

Used by Makefile.mingw (fallback build for machines without CMake).
The CMake build uses cmake/clip_version.h.in directly via configure_file().

Usage:
    python scripts/generate_version_header.py <output_directory>

Writes: output_directory/clip_version.h
"""

import sys
import os
from datetime import datetime, timezone

# ---- Version definitions (keep in sync with CMakeLists.txt) ------------
SW_MAJOR   = 2
SW_MINOR   = 0
SW_PATCH   = 0
PROTO_MAJ  = 1
PROTO_MIN  = 0
MAGIC      = "0x434C4950u"  # ASCII "CLIP"
PLATFORM   = "Windows"

timestamp  = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
sw_str     = f"{SW_MAJOR}.{SW_MINOR}.{SW_PATCH}"
proto_str  = f"{PROTO_MAJ}.{PROTO_MIN}"

header_lines = [
    "/*",
    " * clip_version.h  --  AUTO-GENERATED BY scripts/generate_version_header.py",
    " *                     DO NOT EDIT MANUALLY.",
    " *",
    " * CLICOM - CLI Communication System",
    " *",
    " * IMPORTANT: Software version and protocol version are intentionally separate.",
    " *",
    " *   Software version : tracks binary releases (semantic versioning).",
    " *   Protocol version : governs wire compatibility (CLIPv1.0).",
    " *",
    " * These two versions advance independently. Never conflate them.",
    " * Protocol changes are documented in docs/PROTOCOL_CHANGELOG.md.",
    " */",
    "",
    "#ifndef CLIP_VERSION_H",
    "#define CLIP_VERSION_H",
    "",
    "/* -- Software Version ----------------------------------------------- */",
    f"#define CLICOM_VERSION_MAJOR    {SW_MAJOR}",
    f"#define CLICOM_VERSION_MINOR    {SW_MINOR}",
    f"#define CLICOM_VERSION_PATCH    {SW_PATCH}",
    f'#define CLICOM_VERSION_STRING   "{sw_str}"',
    "",
    "/* -- Protocol Version (CLIPv1) --------------------------------------- */",
    f"#define CLIP_PROTOCOL_VERSION_MAJOR   {PROTO_MAJ}",
    f"#define CLIP_PROTOCOL_VERSION_MINOR   {PROTO_MIN}",
    f'#define CLIP_PROTOCOL_VERSION_STRING  "{proto_str}"',
    "",
    '/* Protocol wire magic: ASCII "CLIP" = 0x43 0x4C 0x49 0x50            */',
    f"#define CLIP_PROTOCOL_MAGIC  {MAGIC}",
    "",
    "/* -- Build Metadata ------------------------------------------------- */",
    f'#define CLICOM_BUILD_TIMESTAMP   "{timestamp}"',
    f'#define CLICOM_TARGET_PLATFORM   "{PLATFORM}"',
    "",
    "#endif /* CLIP_VERSION_H */",
    "",
]

header_content = "\n".join(header_lines)


def main():
    if len(sys.argv) != 2:
        print(f"Usage: python {sys.argv[0]} <output_directory>", file=sys.stderr)
        sys.exit(1)

    out_dir = sys.argv[1]
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "clip_version.h")

    # Always write as ASCII-only so no encoding issues on any platform
    with open(out_path, "w", encoding="ascii", newline="\n") as f:
        f.write(header_content)

    print(f"Generated : {out_path}")
    print(f"  Software  : {sw_str}")
    print(f"  Protocol  : {proto_str}")
    print(f"  Timestamp : {timestamp}")


if __name__ == "__main__":
    main()
